-- tests/client_events.lua -- the events the WoW client actually has.
--
-- Presets declare events in a `$EVENTS` line.  OutfitterScripting routes anything
-- NOT in Outfitter.BuiltinEvents to the client's own RegisterEvent, and the
-- comment at Outfitter.lua:466 records that since patch 8.0 the client RAISES on
-- an event that does not exist.  So a typo in a preset's $EVENTS line is a crash,
-- not a dead preset -- which is what tests/test_scripts.lua checks against this.
--
-- DERIVED, NOT TYPED.  Extracted from Blizzard's published UI source
-- (https://github.com/Gethe/wow-ui-source, live branch) by collecting every
-- argument to RegisterEvent / RegisterUnitEvent and every `event == "..."`
-- comparison across the tree. 1523 names. Regenerate the same way when the client
-- gains events a preset wants; do not hand-add a name to make a test pass.
--
-- It is a broad net rather than an exhaustive registry: an event Blizzard's own
-- UI never registers for will not be here. That direction is the safe one -- it
-- reports a preset for review rather than letting a bad name through.

